import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_CHANNEL ? {channel:process.env.BROWSER_CHANNEL} : {}) })
const base = process.env.STOREFRONT_URL || 'http://127.0.0.1:5173'
const page = await browser.newPage({viewport:{width:1440,height:1000}})
const errors = []
page.on('pageerror', error => errors.push(error.message))
const goto = async path => { await page.goto(base + path); await page.locator('main h1:visible').first().waitFor() }
const message = async locator => new URL(await locator.getAttribute('href')).searchParams.get('text')
const main = page.locator('main')
try {
  await goto('/')
  const search = page.locator('header').getByRole('searchbox')
  await search.fill('caneca jesus')
  await page.locator('header').getByRole('button',{name:'Pesquisar produtos',exact:true}).click()
  await page.waitForURL(/busca=/)
  await main.getByRole('heading',{name:'Todos os produtos',exact:true}).waitFor()
  await main.locator('.product-card').first().waitFor()
  const names = await main.locator('.product-card h3').allTextContents()
  assert(names.length > 0 && names.every(name => /caneca/i.test(name) && /jesus/i.test(name)))
  console.log('PASS: busca de produtos e resultados reais')

  await goto('/categoria/camisetas')
  const aside = main.getByRole('complementary')
  const shirtCount = await main.locator('.product-card').count()
  assert(shirtCount > 0)
  await aside.getByLabel('Tecido',{exact:true}).selectOption('algodao')
  await aside.getByLabel('Modelo',{exact:true}).selectOption('oversized')
  await page.waitForURL(url => url.searchParams.get('tecido') === 'algodao' && url.searchParams.get('modelo') === 'oversized')
  await main.getByRole('button',{name:'Remover filtro Oversized',exact:true}).click()
  await aside.getByRole('slider',{name:'Preço máximo no controle deslizante'}).fill('40')
  await main.getByRole('heading',{name:'Nenhum produto encontrado'}).waitFor()
  await aside.getByRole('button',{name:'Limpar',exact:true}).click()
  await main.getByRole('heading',{name:'Todos os produtos',exact:true}).waitFor()
  await aside.getByRole('checkbox',{name:/^Camisetas/}).check()
  await page.waitForFunction(count => document.querySelectorAll('main .product-card').length === count,shirtCount)
  await aside.getByLabel('Tecido',{exact:true}).selectOption('poliester')
  await aside.getByRole('slider',{name:'Preço máximo no controle deslizante'}).fill('40')
  assert.equal(await main.locator('.product-card').count(),shirtCount)
  console.log('PASS: tecido, modelo, preço por tecido, remoção e limpeza de filtros')

  await goto('/produtos?ordem=menor-preco')
  const prices = (await main.locator('.product-price').allTextContents()).map(value=>Number(value.replace(/[^\d,]/g,'').replace(',','.')))
  assert.deepEqual(prices,[...prices].sort((a,b)=>a-b))
  await goto('/categoria/canecas?tipo=colorir')
  assert((await main.locator('.product-card h3').allTextContents()).every(name=>name.includes('Pintar')))
  await goto('/produtos?busca=produto-inexistente-qa')
  await main.getByRole('heading',{name:'Nenhum produto encontrado'}).waitFor()
  console.log('PASS: ordenação, tipo de caneca e busca sem resultados')

  await goto('/produto/camiseta-100-algodao-personalizada')
  await main.getByRole('button',{name:'Poliéster',exact:true}).click()
  await main.getByRole('button',{name:/^GG/}).click()
  await main.getByRole('button',{name:'Consultar outras cores',exact:true}).click()
  const originalImage = await main.locator('img').first().getAttribute('src')
  await main.getByRole('button',{name:'Azul',exact:true}).click()
  assert.equal(await main.locator('img').first().getAttribute('src'),originalImage)
  await main.getByLabel('Nome para personalização',{exact:true}).fill('Maria QA')
  await main.getByLabel('Texto da estampa',{exact:true}).fill('Fé e propósito')
  await main.getByLabel('Observações para o pedido',{exact:true}).fill('Arte centralizada')
  await main.getByRole('spinbutton',{name:'Quantidade',exact:true}).fill('2')
  const directMessage = await message(main.getByRole('link',{name:'Solicitar orçamento pelo WhatsApp',exact:true}))
  for (const text of ['Poliéster','GG','Azul','Maria QA','Fé e propósito','Arte centralizada','Quantidade:* 2']) assert(directMessage.includes(text),text)
  await main.getByRole('button',{name:/^Oversized/}).click()
  await page.waitForFunction(()=>document.querySelector('main button:disabled')?.textContent.includes('Adicionar') || [...document.querySelectorAll('main button')].some(b=>b.disabled && b.textContent.includes('Adicionar')))
  await main.getByRole('button',{name:'Tradicional',exact:true}).click()
  await main.getByRole('button',{name:'Adicionar à sacola',exact:true}).click()
  const drawer = page.getByRole('dialog',{name:'Minha sacola',exact:true})
  await drawer.waitFor()
  assert((await drawer.innerText()).includes('Maria QA'))
  await drawer.getByRole('link',{name:'Ver sacola completa',exact:true}).click()
  await page.waitForURL(/\/sacola$/)
  await main.getByRole('heading',{name:'Minha sacola',exact:true}).waitFor()
  const cartMessage = await message(main.getByRole('link',{name:'Enviar pedido pelo WhatsApp',exact:true}))
  for (const text of ['Poliéster','GG','Azul','Maria QA','Fé e propósito','Arte centralizada','Quantidade: 2','76,00']) assert(cartMessage.includes(text),text)
  await page.reload()
  await main.getByRole('link',{name:'Editar opções ou personalização',exact:true}).waitFor()
  await main.getByRole('link',{name:'Editar opções ou personalização',exact:true}).click()
  await main.getByRole('button',{name:'Salvar alterações na sacola',exact:true}).waitFor()
  assert.equal(await main.getByLabel('Nome para personalização',{exact:true}).inputValue(),'Maria QA')
  assert.equal(await main.getByRole('spinbutton',{name:'Quantidade',exact:true}).inputValue(),'2')
  assert.equal(await main.getByRole('button',{name:'Poliéster',exact:true}).getAttribute('aria-pressed'),'true')
  await main.getByLabel('Nome para personalização',{exact:true}).fill('Ana QA')
  await main.getByRole('button',{name:'Salvar alterações na sacola',exact:true}).click()
  await page.waitForURL(/\/sacola$/)
  await main.getByRole('heading',{name:'Minha sacola',exact:true}).waitFor()
  assert.equal(await main.locator('ul > li').count(),1)
  assert((await message(main.getByRole('link',{name:'Enviar pedido pelo WhatsApp',exact:true}))).includes('Ana QA'))
  await main.getByRole('button',{name:/^Aumentar quantidade de/}).click()
  assert((await message(main.getByRole('link',{name:'Enviar pedido pelo WhatsApp',exact:true}))).includes('Quantidade: 3'))
  console.log('PASS: opções distintas, cor sem foto fictícia, personalização, orçamento direto, sacola, persistência, edição e totais')

  for (const width of [320,390,768,1024,1440]) {
    await page.setViewportSize({width,height:900})
    for (const path of ['/','/produtos','/produto/camiseta-100-algodao-personalizada','/sacola']) {
      await goto(path)
      const overflow = await page.evaluate(()=>({viewport:innerWidth,width:document.documentElement.scrollWidth}))
      assert(overflow.width <= overflow.viewport,`Overflow ${path} at ${width}: ${JSON.stringify(overflow)}`)
    }
  }
  console.log('PASS: sem rolagem horizontal em 20 combinações de página/largura (320 a 1440px)')

  await page.setViewportSize({width:390,height:844})
  await goto('/categoria/camisetas')
  const filterTrigger = main.getByRole('button',{name:/Filtrar/})
  await filterTrigger.click()
  const filters = page.getByRole('dialog',{name:'Filtros de produtos',exact:true})
  await filters.waitFor()
  assert(await filters.evaluate(element=>element.contains(document.activeElement)))
  await filters.getByLabel('Modelo',{exact:true}).selectOption('tradicional')
  await filters.getByRole('button',{name:/Ver resultados/}).focus()
  await page.keyboard.press('Tab')
  assert(await filters.evaluate(element=>element.contains(document.activeElement)))
  await page.keyboard.press('Escape')
  assert.equal(await filters.count(),0)
  assert(await filterTrigger.evaluate(element=>element===document.activeElement))
  await page.getByRole('button',{name:'Abrir menu',exact:true}).click()
  await page.getByRole('dialog',{name:'Menu de navegação',exact:true}).waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:/Abrir sacola/}).click()
  await page.getByRole('dialog',{name:'Minha sacola',exact:true}).waitFor()
  await page.keyboard.press('Escape')
  console.log('PASS: painéis mobile, foco contido, Escape e retorno do foco')

  await goto('/sacola')
  await main.getByRole('button',{name:/^Remover .* da sacola$/}).click()
  await main.getByRole('link',{name:/Explorar|Ver produtos|Conhecer/}).waitFor()
  assert.equal(await main.getByRole('link',{name:'Enviar pedido pelo WhatsApp',exact:true}).count(),0)
  assert.deepEqual(errors,[])
  console.log('PASS: remoção e sacola vazia; nenhum erro JavaScript')
} finally { await browser.close() }
