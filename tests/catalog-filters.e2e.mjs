import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_CHANNEL ? { channel: process.env.BROWSER_CHANNEL } : {}) })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const base = process.env.STOREFRONT_URL || 'http://127.0.0.1:5173'
const errors = []
page.on('pageerror', error => errors.push(error.message))
const main = page.locator('main')
const expectValue = async (locator, value) => {
  const id = await locator.getAttribute('id')
  await page.waitForFunction(([id, value]) => document.getElementById(id)?.value === value, [id, value])
}
const go = async path => { await page.goto(base + path); await main.locator('h1:visible').first().waitFor() }
const expectCount = async count => {
  await page.waitForFunction(expected => document.querySelectorAll('main .product-card').length === expected, count)
  assert.match(await main.locator('.catalog-result-count').innerText(), new RegExp(`^${count} produto`))
}
const artifacts = process.env.STOREFRONT_ARTIFACTS
const capture = async name => { if (artifacts) { await mkdir(artifacts, { recursive: true }); await page.screenshot({ path: `${artifacts}/${name}.png`, animations: 'disabled' }) } }
try {
  await go('/')
  const hero = main.locator('.hero-slide.is-active')
  assert.equal(await hero.locator('h1').innerText(), 'Personalizados que expressam sua fé e seu estilo.')
  assert.equal(await hero.locator('.hero-description').innerText(), 'Camisas e canecas feitas para você e para quem você ama.')
  const photo = hero.getByRole('img')
  await photo.evaluate(img => img.decode())
  const imageInfo = await photo.evaluate(img => ({ width: img.clientWidth, naturalWidth: img.naturalWidth, naturalHeight: img.naturalHeight, fit: getComputedStyle(img).objectFit }))
  assert.equal(imageInfo.naturalWidth, 2078)
  assert.equal(imageInfo.naturalHeight, 757)
  assert(imageInfo.width <= imageInfo.naturalWidth)
  assert.equal(imageInfo.fit, 'cover')
  assert.equal(await hero.getByRole('link', { name: 'Explorar produtos' }).getAttribute('href'), '/produtos')
  const whatsapp = new URL(await hero.getByRole('link', { name: 'Pedir pelo WhatsApp' }).getAttribute('href'))
  assert.equal(whatsapp.hostname, 'wa.me')
  assert(whatsapp.searchParams.get('text'))
  await capture('banner-desktop')
  console.log('PASS: banner horizontal, resolução útil, enquadramento e destinos dos botões')

  await go('/produtos')
  const all = await page.evaluate(async () => {
    const { PRODUCTS } = await import('/src/data/products.ts')
    return PRODUCTS.filter(product => product.available && product.status !== 'draft')
  })
  await expectCount(all.length)
  const aside = main.getByRole('complementary')
  assert.equal(Math.round((await aside.boundingBox()).width), 260)
  assert.equal(await aside.getByRole('checkbox').count(), 6)
  for (const category of ['canecas', 'camisetas', 'copos', 'kits', 'quadros', 'personalizados']) {
    const expected = all.filter(product => product.category === category).length
    const label = await aside.locator('.category-option').nth(['canecas','camisetas','copos','kits','quadros','personalizados'].indexOf(category)).innerText()
    assert(label.trim().endsWith(String(expected)))
  }
  assert.equal(await aside.getByRole('button', { name: 'Limpar', exact: true }).count(), 0)
  assert.equal(await aside.getByLabel('Ordenar por').count(), 0)
  await aside.getByRole('checkbox', { name: /^Canecas/ }).check()
  await aside.getByRole('checkbox', { name: /^Camisetas/ }).check()
  await expectCount(all.filter(product => ['canecas','camisetas'].includes(product.category)).length)
  assert.deepEqual(new URL(page.url()).searchParams.getAll('categoria'), ['canecas','camisetas'])
  await capture('filtros-desktop')
  console.log('PASS: coluna de 260px, seis categorias e contagens reais; categorias combinadas como alternativas')

  await aside.getByLabel('Mínimo', { exact: true }).fill('R$ 40,00')
  await aside.getByLabel('Mínimo', { exact: true }).press('Tab')
  await aside.getByLabel('Máximo', { exact: true }).fill('R$ 45,00')
  await aside.getByLabel('Máximo', { exact: true }).press('Tab')
  const categoryPrice = all.filter(product => ['canecas','camisetas'].includes(product.category) && product.price >= 40 && product.price <= 45)
  await expectCount(categoryPrice.length)
  await expectValue(aside.getByRole('slider', { name: 'Preço mínimo no controle deslizante' }), '40')
  await expectValue(aside.getByRole('slider', { name: 'Preço máximo no controle deslizante' }), '45')
  const search = main.getByRole('searchbox')
  await search.fill('Jesus')
  await main.getByRole('button', { name: 'Pesquisar produtos', exact: true }).click()
  await expectCount(categoryPrice.filter(product => /jesus/i.test(product.name)).length)
  await main.getByRole('button', { name: 'Remover filtro Canecas', exact: true }).click()
  await expectCount(0)
  await main.getByRole('heading', { name: 'Nenhum produto encontrado', exact: true }).waitFor()
  await main.getByRole('button', { name: 'Limpar filtros', exact: true }).click()
  await expectCount(all.length)
  assert.equal(await aside.getByRole('checkbox', { checked: true }).count(), 0)
  console.log('PASS: busca AND faixa de preço AND categorias; remoção individual e limpeza sem resultados')

  await aside.getByRole('slider', { name: 'Preço mínimo no controle deslizante' }).fill('35')
  await aside.getByRole('slider', { name: 'Preço máximo no controle deslizante' }).fill('45')
  await expectValue(aside.getByLabel('Mínimo', { exact: true }), 'R$ 35,00')
  await expectValue(aside.getByLabel('Máximo', { exact: true }), 'R$ 45,00')
  const lowerSlider = aside.getByRole('slider', { name: 'Preço mínimo no controle deslizante' })
  const upperSlider = aside.getByRole('slider', { name: 'Preço máximo no controle deslizante' })
  await lowerSlider.focus()
  await lowerSlider.press('ArrowRight')
  await expectValue(lowerSlider, '35.01')
  await upperSlider.focus()
  await upperSlider.press('ArrowLeft')
  await expectValue(upperSlider, '44.99')
  await main.getByRole('button', { name: /^Remover filtro R\$/ }).click()
  await expectCount(all.length)
  await aside.getByLabel('Mínimo', { exact: true }).fill('999')
  await aside.getByLabel('Mínimo', { exact: true }).press('Tab')
  const minimum = Number(await aside.getByRole('slider', { name: 'Preço mínimo no controle deslizante' }).inputValue())
  const maximum = Number(await aside.getByRole('slider', { name: 'Preço máximo no controle deslizante' }).inputValue())
  assert(minimum <= maximum)
  await aside.getByLabel('Máximo', { exact: true }).fill('1')
  await aside.getByLabel('Máximo', { exact: true }).press('Tab')
  assert.equal(await aside.getByRole('slider', { name: 'Preço mínimo no controle deslizante' }).inputValue(), await aside.getByRole('slider', { name: 'Preço máximo no controle deslizante' }).inputValue())
  await aside.getByRole('button', { name: 'Limpar', exact: true }).click()
  await expectCount(all.length)
  await lowerSlider.scrollIntoViewIfNeeded()
  const lowerBox = await lowerSlider.boundingBox()
  await page.mouse.move(lowerBox.x + 10, lowerBox.y + 22)
  await page.mouse.down()
  await page.mouse.move(lowerBox.x + 10 + (lowerBox.width - 20) * .25, lowerBox.y + 22, { steps: 8 })
  await page.mouse.up()
  const upperBox = await upperSlider.boundingBox()
  await page.mouse.move(upperBox.x + upperBox.width - 10, upperBox.y + 22)
  await page.mouse.down()
  await page.mouse.move(upperBox.x + 10 + (upperBox.width - 20) * .75, upperBox.y + 22, { steps: 8 })
  await page.mouse.up()
  assert(Number(await lowerSlider.inputValue()) > Number(await lowerSlider.getAttribute('min')))
  assert(Number(await upperSlider.inputValue()) < Number(await upperSlider.getAttribute('max')))
  await aside.getByRole('button', { name:'Limpar',exact:true }).click()
  await expectCount(all.length)
  console.log('PASS: campos em reais e dois seletores sincronizados; validação, teclado e arraste com mouse')

  const sort = main.getByLabel('Ordenar por', { exact: true })
  await sort.waitFor()
  assert.deepEqual(await sort.locator('option').allTextContents(), ['Mais recentes','Menor preço','Maior preço','Nome de A a Z'])
  for (const order of ['menor-preco','maior-preco']) {
    await sort.selectOption(order)
    await page.waitForURL(url => url.searchParams.get('ordem') === order)
    await expectValue(sort, order)
    const prices = (await main.locator('.product-price').allTextContents()).map(text => Number(text.replace(/[^\d,]/g, '').replace(',', '.')))
    assert.deepEqual(prices, [...prices].sort(order === 'menor-preco' ? (a,b)=>a-b : (a,b)=>b-a))
  }
  await sort.selectOption('nome')
  await page.waitForURL(url => url.searchParams.get('ordem') === 'nome')
  await expectValue(sort, 'nome')
  const names = await main.locator('.product-card h3').allTextContents()
  assert.deepEqual(names, [...names].sort((a,b)=>a.localeCompare(b,'pt-BR')))
  await sort.selectOption('recentes')
  await page.waitForURL(url => !url.searchParams.has('ordem'))
  console.log('PASS: ordenação acima da grade, quatro opções e contagem consistente')

  // A changed catalog proves the upper limit is data-driven and ignores old prices.
  await page.route('**/api/catalog', route => route.fulfill({ json: [{ ...all[0], id:'qa-priced', slug:'qa-priced', price:128.5, oldPrice:250, variants:[] }] }))
  await go('/produtos')
  await expectCount(1)
  assert.equal(await main.getByRole('complementary').getByLabel('Máximo', { exact:true }).inputValue(), 'R$ 128,50')
  await page.unroute('**/api/catalog')
  console.log('PASS: limite real de R$ 128,50 em catálogo simulado, sem usar o preço anterior de R$ 250')

  await page.setViewportSize({width:390,height:844})
  await go('/produtos')
  const trigger = main.getByRole('button', {name:'Filtrar',exact:true})
  await trigger.click()
  const panel = page.getByRole('dialog', { name:'Filtros de produtos',exact:true })
  await panel.getByRole('checkbox', { name:/^Canecas/ }).check()
  await panel.getByRole('checkbox', { name:/^Camisetas/ }).check()
  await panel.getByLabel('Mínimo', {exact:true}).fill('35')
  await panel.getByLabel('Mínimo', {exact:true}).press('Tab')
  await panel.getByRole('button', {name:/Ver resultados/}).click()
  await main.getByRole('button', {name:/Filtrar/}).click()
  assert.equal(await panel.getByRole('checkbox', {checked:true}).count(),2)
  assert.equal(await panel.getByLabel('Mínimo',{exact:true}).inputValue(),'R$ 35,00')
  assert.match(await main.locator('.mobile-filter-trigger').innerText(), /3/)
  await panel.getByRole('button', {name:/Ver resultados/}).focus()
  await page.keyboard.press('Tab')
  assert(await panel.evaluate(element=>element.contains(document.activeElement)))
  await page.keyboard.press('Escape')
  await panel.waitFor({state:'detached'})
  assert.equal(await panel.count(),0)
  assert(await main.locator('.mobile-filter-trigger').evaluate(element=>element===document.activeElement))
  await main.getByRole('button', {name:/Filtrar/}).click()
  await capture('filtros-mobile')
  await panel.getByRole('button', {name:'Limpar',exact:true}).click()
  await expectCount(all.length)
  assert.equal(await panel.getByRole('checkbox', {checked:true}).count(),0)
  await panel.getByRole('button', {name:'Fechar filtros',exact:true}).click()
  console.log('PASS: painel móvel mantém seleções, contador, limpeza, foco, Escape e retorno ao botão')

  for (const width of [320,390,768,1024,1440]) {
    await page.setViewportSize({width,height:900})
    for (const path of ['/','/produtos']) {
      await go(path)
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), `Rolagem horizontal em ${width}px ${path}`)
      if (path === '/') {
        const info = await main.locator('.hero-slide.is-active .hero-scene img').evaluate(img=>({width:img.clientWidth,natural:img.naturalWidth,height:img.clientHeight}))
        assert(info.width <= 2078)
        assert(info.height > 0)
      }
    }
  }
  await page.setViewportSize({width:390,height:844})
  await go('/')
  await photo.evaluate(img=>img.decode())
  await capture('banner-mobile')
  assert.deepEqual(errors,[])
  console.log('PASS: responsividade de 320 a 1440px, composição fotográfica sem deformação e nenhum erro JavaScript')
} finally { await browser.close() }
