import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({headless:true,...(process.env.BROWSER_CHANNEL ? {channel:process.env.BROWSER_CHANNEL} : {})})
const page = await browser.newPage({viewport:{width:1440,height:1000},hasTouch:true})
const base = process.env.STOREFRONT_URL || 'http://127.0.0.1:5173'
const errors=[]
page.on('pageerror', error=>errors.push(error.message))
const active=()=>page.locator('.hero-slide.is-active')
const expectIndex=async index=>page.waitForFunction(index=>document.querySelector('.hero-slide.is-active')?.getAttribute('aria-label')?.startsWith(`${index} de`),index)
try {
  await page.goto(base,{waitUntil:'networkidle'})
  const banners=await page.evaluate(async()=> (await import('/src/data/homeBanners.ts')).HOME_BANNERS)
  assert.deepEqual(banners.map(banner=>banner.id),['gospel','filmes-series','animes-desenhos','games','presentes','modelos-canecas'])
  assert.equal(banners.filter(banner=>banner.image).length,6)
  assert.equal(await page.locator('.hero-slide').count(),6)
  assert.equal(await active().locator('h1').innerText(),'Personalizados que expressam sua fé e seu estilo.')
  assert.equal(await active().locator('img').getAttribute('fetchpriority'),'high')
  assert.equal(await page.locator('.carousel-controls').count(),1)
  await page.reload()
  await expectIndex(1)
  assert.equal(await active().getByRole('link',{name:'Explorar produtos'}).getAttribute('href'),'/produtos')
  assert((await active().getByRole('link',{name:'Pedir pelo WhatsApp'}).getAttribute('href')).startsWith('https://wa.me/'))
  console.log('PASS: seis slides em produção; Gospel inicial após recarga, prioridade alta e destinos reais')

  await page.clock.install()
  await page.clock.pauseAt(new Date())
  await page.goto(base,{waitUntil:'networkidle'})
  await expectIndex(1)
  await page.mouse.move(0,0)
  const initialY=(await page.locator('.service-strip').boundingBox()).y
  await page.clock.fastForward(5999)
  await expectIndex(1)
  await page.clock.fastForward(1)
  await expectIndex(2)
  for(const index of [3,4,5,6,1]) { await page.clock.fastForward(6000); await expectIndex(index); assert.equal((await page.locator('.service-strip').boundingBox()).y,initialY) }
  console.log('PASS: banners reais — ordem, intervalo de seis segundos, retorno ao primeiro e altura estável')

  await page.getByRole('button',{name:'Próximo banner',exact:true}).click()
  await expectIndex(2)
  await page.getByRole('button',{name:'Banner anterior',exact:true}).click()
  await expectIndex(1)
  await page.getByRole('button',{name:'Mostrar banner 5: Presentes personalizados',exact:true}).click()
  await expectIndex(5)
  await page.getByRole('button',{name:'Mostrar banner 6: Modelos de caneca',exact:true}).click()
  await expectIndex(6)
  await page.getByRole('button',{name:'Próximo banner',exact:true}).click()
  await expectIndex(1)
  await page.getByRole('button',{name:'Pausar carrossel',exact:true}).click()
  await page.locator('header').getByRole('searchbox').focus()
  await page.mouse.move(0,0)
  await page.clock.fastForward(12000)
  await expectIndex(1)
  await page.getByRole('button',{name:'Retomar carrossel',exact:true}).click()
  await page.locator('header').getByRole('searchbox').focus()
  await page.mouse.move(0,0)
  await page.clock.fastForward(6000)
  await expectIndex(2)
  await page.locator('.hero-carousel').hover()
  await page.clock.fastForward(12000)
  await expectIndex(2)
  await page.mouse.move(0,0)
  await active().getByRole('link').first().focus()
  await page.clock.fastForward(12000)
  await expectIndex(2)
  await page.locator('.hero-carousel').focus()
  await page.keyboard.press('ArrowRight')
  await expectIndex(3)
  console.log('PASS: setas, indicadores, pausa/retomada, interação com mouse e teclado')

  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto(base,{waitUntil:'networkidle'})
  await expectIndex(1)
  await page.clock.fastForward(18000)
  await expectIndex(1)
  await page.getByRole('button',{name:'Retomar carrossel',exact:true}).waitFor()
  await page.setViewportSize({width:390,height:1000})
  const mobileY=(await page.locator('.service-strip').boundingBox()).y
  const scene=await active().locator('.hero-scene').boundingBox()
  const cdp=await page.context().newCDPSession(page)
  const y=Math.min(scene.y+scene.height/2,900)
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:310,y}]})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:220,y}]})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:75,y}]})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await expectIndex(2)
  assert.equal((await page.locator('.service-strip').boundingBox()).y,mobileY)
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await page.reload()
  await expectIndex(1)
  assert.deepEqual(errors,[])
  console.log('PASS: movimento reduzido, swipe real no celular, altura estável, recarga Gospel e nenhum erro JavaScript')
} finally { await browser.close() }

